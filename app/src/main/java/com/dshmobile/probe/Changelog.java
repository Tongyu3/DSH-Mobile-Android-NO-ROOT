    private Changelog() { }

    /** 全部记录，新的在前。 */
    public static List<Entry> all() {
        return Collections.unmodifiableList(ALL);
    }

    /** 当前版本（读不到就返回 null）。 */
    public static Entry current() {
        return ALL.isEmpty() ? null : ALL.get(0);
    }

    /**
     * 从 {@code fromCode}（不含）到当前版本之间的更新内容，新的在前。
     *
     * <p>{@code fromCode <= 0} 表示"第一次装"，此时只给当前版本这一条 ——
     * 全新安装没必要把历史一次性糊用户一脸。
     */
    public static List<Entry> since(int fromCode) {
        List<Entry> out = new ArrayList<>();
        if (fromCode <= 0) {
            if (current() != null) out.add(current());
            return out;
        }
        for (Entry e : ALL) {
            if (e.code > fromCode) out.add(e);
        }
        return out;
    }
